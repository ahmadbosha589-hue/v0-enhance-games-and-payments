#!/usr/bin/env python3
"""Generate flat-overrides-it.ts / flat-overrides-hi.ts: the it/hi flat blocks
from translations.ts minus the keys the standalone translation files already
carry, exported as plain Record<string,string> modules for get-dictionary.ts."""
import re
import sys
from pathlib import Path

REPO = Path(r"C:/Users/pc/AppData/Local/hermes/cache/scratch/gh-compare")
BSLASH = chr(92)


def find_block_end(src: str, entry_start: int) -> int:
    i = src.index("{", entry_start)
    depth = 0
    in_str = False
    while i < len(src):
        c = src[i]
        if in_str:
            if c == BSLASH:
                i += 2
                continue
            if c == '"':
                in_str = False
        else:
            if c == '"':
                in_str = True
            elif c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    return i
        i += 1
    raise ValueError("unbalanced braces")


PAIR_RE = re.compile(r'\n\s+"([a-zA-Z.]+)":\s*"((?:[^"\\]|\\.)*)"')


def extract_flat_pairs(src: str, entry_pattern: str):
    m = re.search(entry_pattern, src)
    if not m:
        raise SystemExit(f"entry not found: {entry_pattern}")
    close = find_block_end(src, m.start())
    interior = src[src.index("{", m.start()) + 1:close]
    return PAIR_RE.findall(interior)


def main():
    tr_src = (REPO / "lib/i18n/translations.ts").read_text(encoding="utf-8")

    for loc, extra_file, comment in (
        ("it", "italian-translations.ts", "Italian"),
        ("hi", "hindi-translations.ts", "Hindi"),
    ):
        existing = set(
            re.findall(
                r'\n\s+"([a-zA-Z.]+)":',
                (REPO / "lib/i18n" / extra_file).read_text(encoding="utf-8"),
            )
        )
        if loc == "it":
            pattern = r"\n  it: \{"
        else:
            pattern = r"\n  hi: \{"
        pairs = extract_flat_pairs(tr_src, pattern)
        overrides = [(k, v) for k, v in pairs if k not in existing]
        lines = [
            "// Auto-generated by scripts/gen_flat_overrides.py —",
            f"// {comment} flat keys from translations.ts not already present in",
            f"// lib/i18n/{extra_file}. Consumed by get-dictionary.ts to build the",
            f"// {loc} dictionary section; any remaining keys fall back to English",
            "// via deep-merge at module load.",
            'import type { TranslationKey } from "./translations"',
            "",
            f"export const {loc}: Partial<Record<TranslationKey, string>> = {{",
        ]
        for k, v in overrides:
            lines.append(f'  "{k}": "{v}",')
        lines.append("}")
        out = REPO / "lib/i18n" / f"flat-overrides-{loc}.ts"
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{loc}: {len(overrides)} overrides -> {out.name}")


if __name__ == "__main__":
    main()
